import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {FAST_ROUTE,mountQuickRoute} from '../public/quick-route.js';
const events={},calls=[];
const engineering={addEventListener:(name,fn)=>events.engineering=fn};
const production={addEventListener:(name,fn)=>events.production=fn};
const heading={setAttribute:(k,v)=>calls.push(['heading',k,v]),focus:options=>calls.push(['focus',options])};
const lookup={'[data-quick-stop="engineering"]':engineering,'[data-quick-stop="production"]':production,'#flagship-record':{click:()=>calls.push('aster-record')},'[data-edition="bmo"]':{click:()=>calls.push('bmo-edition')},'#press-headline':heading};
mountQuickRoute({querySelector:key=>lookup[key]});
events.engineering();assert.deepEqual(calls,['aster-record']);calls.length=0;
events.production({button:0});assert.deepEqual(calls,['bmo-edition',['heading','tabindex','-1'],['focus',{preventScroll:true}]]);
calls.length=0;events.production({button:0,ctrlKey:true});assert.deepEqual(calls,[],'modified navigation keeps native behavior');
const html=readFileSync(new URL('../portfolio.html',import.meta.url),'utf8');
assert.equal((html.match(/data-quick-stop=/g)||[]).length,3,'only three presets');
assert.match(html,/href="#highlights" class="line-link">Take the short route/);
assert.match(html,/href="#press-headline" data-quick-stop="production"/);
assert.match(html,/href="\/resume.html" data-quick-stop="resume"/);
assert.equal(FAST_ROUTE.resume.href,'/resume.html');
assert.match(html,/role="group" aria-label="Choose an object"/,'existing free exploration retained');
console.log('Quick route: three presets, direct ASTER record, BMO edition/focus, native résumé link and modified navigation pass.');
